#!/usr/bin/env python3
"""Generate crates/pdfi-font/src/std14.rs: the built-in encodings of Symbol
and ZapfDingbats and the glyph widths of the standard 14 fonts (Adobe's
Core14 AFM files), taken from the generated tables of hayro-interpret
(MIT / Apache-2.0).

Usage: python3 -I scripts/gen-font-std14.py <hayro-interpret-0.8.0/src/font/generated> \
         > crates/pdfi-font/src/std14.rs
"""
import re
import sys

src = sys.argv[1]


def blocks(path):
    text = open(f"{src}/{path}").read()
    for m in re.finditer(r"static (\w+): phf::Map<[^>]*> = phf_map! \{(.*?)\};", text, re.S):
        yield m.group(1), m.group(2)


def encoding(path):
    (_, body), = blocks(path)
    names = [""] * 256
    for code, name in re.findall(r'(\d+)_u8 => "([^"]+)"', body):
        names[int(code)] = name
    return names


print("// Generated by scripts/gen-font-std14.py from hayro-interpret's tables")
print("// (MIT / Apache-2.0), which come from Adobe's Core14 AFM files; do not edit.\n")
for const, path in (("SYMBOL", "symbol.rs"), ("ZAPF_DINGBATS", "zapf_dings.rs")):
    names = encoding(path)
    print(f"/// Built-in encoding of {const.title().replace('_', '')}.")
    print(f"pub static {const}_ENCODING: [&str; 256] = [")
    for i in range(0, 256, 8):
        print("    " + " ".join(f'"{n}",' for n in names[i : i + 8]))
    print("];\n")

fonts = []
for name, body in blocks("metrics.rs"):
    widths = sorted((n, round(float(w))) for n, w in re.findall(r'"([^"]+)" => ([\d.]+)_f32', body))
    fonts.append((name, widths))
for name, widths in fonts:
    print(f"pub static {name}_WIDTHS: [(&str, u16); {len(widths)}] = [")
    for n, w in widths:
        print(f'    ("{n}", {w}),')
    print("];\n")
