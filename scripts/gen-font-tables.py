#!/usr/bin/env python3
"""Generate crates/pdfi-font/src/tables.rs: the base encodings by glyph name
and the Adobe Glyph List (glyph name -> Unicode), from fontTools.

Usage: python3 -I scripts/gen-font-tables.py > crates/pdfi-font/src/tables.rs
"""
from fontTools import agl
from fontTools.encodings.MacRoman import MacRoman
from fontTools.encodings.StandardEncoding import StandardEncoding


def clean(names):
    out = []
    for code, n in enumerate(names):
        out.append("" if code < 32 or code == 127 or n in (".notdef", None) else n)
    return out


standard = clean(StandardEncoding)

# PDF's MacRomanEncoding (Annex D): as Mac OS Roman, but 0xDB is currency,
# 0xF0 (the Apple logo) is unused and 0xCA is a space.
mac = clean(MacRoman)
mac[0xDB] = "currency"
mac[0xF0] = ""
mac[0xCA] = "space"

# WinAnsiEncoding: code page 1252; unused codes above 0x20 show a bullet,
# 0xA0 is a space and 0xAD a hyphen.
win = [""] * 256
for code in range(32, 256):
    if code in (0x7F, 0x81, 0x8D, 0x8F, 0x90, 0x9D):
        win[code] = "bullet"
        continue
    ch = bytes([code]).decode("cp1252")
    win[code] = agl.UV2AGL.get(ord(ch), "uni%04X" % ord(ch))
win[0xA0] = "space"
win[0xAD] = "hyphen"

glyphs = {}
for name, uvs in agl.LEGACY_AGL2UV.items():
    glyphs[name] = uvs[0]
for name, uv in agl.AGL2UV.items():
    glyphs[name] = uv


def table(name, doc, names):
    print(f"/// {doc}")
    print(f"pub static {name}: [&str; 256] = [")
    for i in range(0, 256, 8):
        print("    " + " ".join(f'"{n}",' for n in names[i : i + 8]))
    print("];\n")


print("// Generated by scripts/gen-font-tables.py from fontTools; do not edit.")
print("// The Adobe Glyph List is (c) Adobe Systems, BSD-3-Clause.\n")
table("STANDARD", "`StandardEncoding` (empty: no glyph).", standard)
table("MAC_ROMAN", "`MacRomanEncoding`.", mac)
table("WIN_ANSI", "`WinAnsiEncoding`.", win)
print("/// Adobe Glyph List: glyph name → Unicode, sorted by name.")
print(f"pub static GLYPH_LIST: [(&str, u16); {len(glyphs)}] = [")
for name in sorted(glyphs):
    print(f'    ("{name}", 0x{glyphs[name]:04x}),')
print("];")
